// Package coremodule writes what lets `go install` bring the docattest core: a Go module
// per platform that embeds that platform's core, and the files of the launcher's
// `bundled` package that import them.
package coremodule

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/docattest/docattest/adapters/go/internal/platform"
)

// Platform is a platform a core is built for, as docattest names it (`linux-x64`).
type Platform string

// goNames are Go's names for a platform's system and processor.
func (p Platform) goNames() (goos, goarch string) {
	return platform.GoNames(string(p))
}

// binaryName is the file name of the core on a platform.
func (p Platform) binaryName() string {
	goos, _ := p.goNames()
	return platform.Executable(goos, "docattest")
}

// ModulePath is the module that carries a platform's core, below a base path.
func ModulePath(base string, p Platform) string {
	return base + "/core-" + string(p)
}

// WriteModule writes the module that carries one platform's core into a directory:
// its go.mod, the core itself, and a file that embeds it.
func WriteModule(dir, base string, p Platform, core []byte) error {
	files := map[string]string{
		"go.mod": fmt.Sprintf("module %s\n\ngo 1.21\n", ModulePath(base, p)),
		"core.go": fmt.Sprintf(`// Code generated by tools/coremodule. DO NOT EDIT.

// Package core is the docattest core for %s, as bytes.
package core

import _ "embed"

// Binary is the docattest core.
//
//go:embed %s
var Binary []byte
`, p, p.binaryName()),
		p.binaryName(): string(core),
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, text := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(text), 0o755); err != nil {
			return err
		}
	}
	return nil
}

// LinkFile is the file of the launcher's `bundled` package that takes a platform's core
// from its module: its name, which makes the go command build it on that platform only,
// and its text.
func LinkFile(base string, p Platform) (name, text string) {
	goos, goarch := p.goNames()
	name = fmt.Sprintf("core_%s_%s.go", goos, goarch)
	text = fmt.Sprintf(`// Code generated by tools/coremodule. DO NOT EDIT.

package bundled

import core %q

func init() { binary = core.Binary }
`, ModulePath(base, p))
	return name, text
}
